-- =====================================================================
-- Factory dataset: synthetic SQL practice data (PostgreSQL)
-- One production day (2026-11-02), 5 machines on 3 production lines.
-- The data intentionally contains real-world issues:
--   * duplicate sensor readings (at-least-once delivery)
--   * missing temperature values (sensor offline)
--   * an alarm that is still active (ts_end IS NULL)
-- Usage: create a database (e.g. "factory") and run this whole file.
-- =====================================================================

DROP TABLE IF EXISTS alarms;
DROP TABLE IF EXISTS machine_states;
DROP TABLE IF EXISTS readings;
DROP TABLE IF EXISTS machines;

CREATE TABLE machines (
    machine_id   INT PRIMARY KEY,
    machine_name VARCHAR(50) NOT NULL,
    line         VARCHAR(20) NOT NULL,
    machine_type VARCHAR(30) NOT NULL
);

-- Hourly sensor readings (like tags archived in a process historian).
CREATE TABLE readings (
    reading_id   INT PRIMARY KEY,
    machine_id   INT NOT NULL REFERENCES machines(machine_id),
    ts           TIMESTAMP NOT NULL,
    temperature  NUMERIC(5,1),          -- degrees C
    pressure     NUMERIC(7,2)           -- bar
);

-- Machine state change events (logged only on change, like a signal edge).
CREATE TABLE machine_states (
    state_id     INT PRIMARY KEY,
    machine_id   INT NOT NULL REFERENCES machines(machine_id),
    ts           TIMESTAMP NOT NULL,
    state        VARCHAR(10) NOT NULL   -- RUNNING / STOPPED / FAULT
);

-- Alarms. ts_end IS NULL means the alarm is still active.
CREATE TABLE alarms (
    alarm_id     INT PRIMARY KEY,
    machine_id   INT NOT NULL REFERENCES machines(machine_id),
    ts_start     TIMESTAMP NOT NULL,
    ts_end       TIMESTAMP,
    alarm_code   VARCHAR(10) NOT NULL,
    description  VARCHAR(100) NOT NULL,
    priority     INT NOT NULL           -- 1 = highest
);

